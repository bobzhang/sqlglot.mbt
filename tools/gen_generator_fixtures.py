def canonical(node):
    """`gen_fixtures.canonical` plus `#t=` (the `_type` of a node) for typed nodes."""
    from sqlglot import exp

    s = _canonical(node)
    return s


def canonical_typed(node):
    from sqlglot import exp

    def val(v):
        if isinstance(v, exp.Expr):
            return canonical_typed(v)
        if isinstance(v, list):
            return "[" + ",".join(val(x) or scalar(x) for x in v if x is not None) + "]"
        return None

    import json
    from sqlglot.expressions import DType

    def scalar(v):
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, DType):
            return "DType." + v.name
        if isinstance(v, int):
            return str(v)
        if isinstance(v, str):
            return json.dumps(v, ensure_ascii=False)
        return json.dumps(str(v), ensure_ascii=False)

    order = list(type(node).arg_types)
    keys = [k for k in order if k in node.args] + sorted(k for k in node.args if k not in order)
    parts = []
    for k in keys:
        v = node.args[k]
        if v is None:
            continue
        r = val(v)
        parts.append(f"{k}={r if r is not None else scalar(v)}")
    if node.comments:
        parts.append("#c=" + json.dumps(node.comments, ensure_ascii=False))
    t = node._type
    if t is not None and not node.is_data_type:
        parts.append("#t=" + canonical_typed(t))
    return f"{type(node).__name__}({','.join(parts)})"
