def dialect_cases(path):
    import json
    import sqlglot

    seen = set()
    res = []
    for line in open(path):
        c = json.loads(line)
        if "error" in c or c.get("kind") not in ("identity", "all", "transpile"):
            continue
        read = c.get("read") or ""
        sql = c.get("sql")
        if not isinstance(sql, str) or (read, sql) in seen:
            continue
        seen.add((read, sql))
        try:
            e = sqlglot.parse_one(sql, read=read or None)
            if e is None:
                continue
            ast = canonical_typed(e)
            out = e.sql()
            pretty = e.sql(pretty=True)
            ident = e.sql(identify=True)
        except Exception:
            continue
        res.append([read + ": " + sql, ast, out, pretty, ident])
    return res


def cases():
    import sqlglot

    seen = set()

    def add(sql, expected_pretty=None):
        try:
            e = sqlglot.parse_one(sql)
        except Exception:
            return None
        if e is None:
            return None
        try:
            ast = canonical_typed(e)
            out = e.sql()
            pretty = e.sql(pretty=True) if expected_pretty is None else expected_pretty
            ident = e.sql(identify=True)
        except Exception:
            return None
        key = (ast, out, pretty, ident)
        if key in seen:
            return None
        seen.add(key)
        return [sql, ast, out, pretty, ident]

    res = []
    for line in open(os.path.join(SG, "tests/fixtures/identity.sql")):
        line = line.rstrip("\n")
        if not line.strip():
            continue
        c = add(line)
        if c:
            res.append(c)

    sys.path.insert(0, os.path.join(SG, "tests"))
    from helpers import load_sql_fixture_pairs

    for _, src, expected in load_sql_fixture_pairs("pretty.sql"):
        c = add(src, expected_pretty=expected)
        if c:
            res.append(c)
    return res


def main():
    os.makedirs(OUT, exist_ok=True)
    res = cases()
    with open(os.path.join(OUT, "generator_fixture_data_test.mbt"), "w") as f:
        f.write("// Code generated by tools/gen_generator_fixtures.py. DO NOT EDIT.\n\n")
        f.write("///|\n")
