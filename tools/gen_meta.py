def gen_dtypes():
    DT = exp.DataType
    names = [t.name for t in exp.DType]
    values = [t.value for t in exp.DType]
    lines = ["// Code generated by tools/gen_meta.py. DO NOT EDIT.", ""]
    lines.append("///|")
    lines.append("pub(all) enum DType {")
    for n in names:
        lines.append(f"  {n}")
    lines.append("} derive(Eq, Hash, Compare)")
    lines.append("")
    lines.append("///|")
    lines.append("pub fn DType::id(self : DType) -> Int {")
    lines.append("  match self {")
    for i, n in enumerate(names):
        lines.append(f"    {n} => {i}")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("pub let all_dtypes : FixedArray[DType] = [")
    for n in names:
        lines.append(f"  {n},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("let dtype_names : FixedArray[String] = [")
    for n in names:
        lines.append(f"  {mbt_str(n)},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("let dtype_values : FixedArray[String] = [")
    for v in values:
        lines.append(f"  {mbt_str(v)},")
    lines.append("]")
    lines.append("")
    for attr in sorted(a for a in dir(DT) if a.endswith("_TYPES") or a.endswith("TYPES") and a.isupper()):
        v = getattr(DT, attr)
        if not isinstance(v, (set, frozenset)):
            continue
        members = sorted(x.name for x in v)
        lines.append("///|")
        lines.append(f"pub let dtype_{attr.lower()} : Array[DType] = [")
        for m in members:
            lines.append(f"  {m},")
        lines.append("]")
        lines.append("")
    with open(os.path.join(OUT, "gen_dtypes.mbt"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    gen_kinds()
    gen_token_types()
    gen_dtypes()
